package com.blake.pmis.entity.enumeration;

/**
 * Patent attachment category.
 * DISCLOSURE: invention disclosure document (.doc/.docx), visible to creator + patent admins only.
 * NOTICE: official CNIPA notices (usually archives), visible to everyone.
 * OTHER: payment receipts etc., visible to everyone.
 */
public enum PatentAttachmentCategory {
    DISCLOSURE,
    NOTICE,
    OTHER
}
